-- Skema PostgreSQL untuk Supabase, disusun dari dump MySQL terbaru yang tersedia.
-- Jalankan di Supabase SQL Editor pada project BARU/kosong. Ini tidak menyalin data.

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama VARCHAR(100) NOT NULL,
  username VARCHAR(50) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(20) DEFAULT 'petugas' CHECK (role IN ('admin','petugas')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  foto_profil VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS pelanggan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama VARCHAR(100) NOT NULL,
  telepon VARCHAR(20) NOT NULL UNIQUE,
  email VARCHAR(100),
  alamat TEXT,
  catatan TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  password VARCHAR(255),
  foto_profil VARCHAR(255)
);

ALTER TABLE pelanggan ADD COLUMN IF NOT EXISTS foto_profil VARCHAR(255);

CREATE TABLE IF NOT EXISTS servis (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nomor_servis VARCHAR(30) NOT NULL UNIQUE,
  nama_pelanggan VARCHAR(100) NOT NULL,
  telepon VARCHAR(20) NOT NULL,
  nomor_polisi VARCHAR(20) NOT NULL,
  jenis_motor VARCHAR(100) NOT NULL,
  keluhan TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'Antre' CHECK (status IN ('Antre','Pengerjaan','Selesai')),
  estimasi_selesai TIMESTAMP,
  selesai_pada TIMESTAMP,
  catatan_petugas TEXT,
  alasan_keterlambatan TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  id_pelanggan BIGINT REFERENCES pelanggan(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS riwayat_servis (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_servis BIGINT NOT NULL REFERENCES servis(id) ON DELETE CASCADE,
  status_sebelumnya VARCHAR(20) CHECK (status_sebelumnya IS NULL OR status_sebelumnya IN ('Antre','Pengerjaan','Selesai')),
  status_baru VARCHAR(20) CHECK (status_baru IS NULL OR status_baru IN ('Antre','Pengerjaan','Selesai')),
  estimasi_sebelumnya TIMESTAMP,
  estimasi_baru TIMESTAMP,
  keterangan TEXT,
  dibuat_oleh BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS notifikasi_wa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_servis BIGINT NOT NULL REFERENCES servis(id) ON DELETE CASCADE,
  telepon_tujuan VARCHAR(20) NOT NULL,
  jenis_notifikasi VARCHAR(40) NOT NULL CHECK (jenis_notifikasi IN ('Status Servis','Estimasi Berubah','Motor Siap Diambil')),
  pesan TEXT NOT NULL,
  status_pengiriman VARCHAR(20) NOT NULL DEFAULT 'menunggu' CHECK (status_pengiriman IN ('menunggu','terkirim','gagal')),
  referensi_api VARCHAR(100),
  respons_api TEXT,
  jumlah_percobaan SMALLINT NOT NULL DEFAULT 0 CHECK (jumlah_percobaan >= 0),
  dikirim_pada TIMESTAMP,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS remember_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  selector CHAR(24) NOT NULL UNIQUE,
  token_hash CHAR(64) NOT NULL,
  expires_at TIMESTAMP NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_servis_created_at ON servis(created_at);
CREATE INDEX IF NOT EXISTS idx_servis_status ON servis(status);
CREATE INDEX IF NOT EXISTS idx_servis_pelanggan ON servis(id_pelanggan);
CREATE INDEX IF NOT EXISTS idx_riwayat_servis_id ON riwayat_servis(id_servis);
CREATE INDEX IF NOT EXISTS idx_notifikasi_servis_id ON notifikasi_wa(id_servis);
CREATE INDEX IF NOT EXISTS idx_remember_user ON remember_tokens(user_id);

-- Menjaga updated_at otomatis seperti perilaku ON UPDATE MySQL.
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS TRIGGER AS $$
BEGIN NEW.updated_at = CURRENT_TIMESTAMP; RETURN NEW; END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS pelanggan_set_updated_at ON pelanggan;
CREATE TRIGGER pelanggan_set_updated_at BEFORE UPDATE ON pelanggan FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS servis_set_updated_at ON servis;
CREATE TRIGGER servis_set_updated_at BEFORE UPDATE ON servis FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS notifikasi_wa_set_updated_at ON notifikasi_wa;
CREATE TRIGGER notifikasi_wa_set_updated_at BEFORE UPDATE ON notifikasi_wa FOR EACH ROW EXECUTE FUNCTION set_updated_at();
